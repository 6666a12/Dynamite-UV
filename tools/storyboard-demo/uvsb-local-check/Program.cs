using System.Buffers.Binary;
using System.Globalization;
using System.Text;
using System.Text.Json;
using DynamiteUniverse.Shared.Storyboard;

var preview = args.Contains("--preview-budget", StringComparer.Ordinal);
var operands = args.Where(arg => arg != "--preview-budget").ToArray();
if (operands.Length is < 1 or > 2 || args.Length - operands.Length > 1 ||
    operands.Any(arg => arg.StartsWith("--", StringComparison.Ordinal)))
{
    Console.Error.WriteLine("usage: UvsbLocalCheck <generated-excerpt-pack> [measurement-start-ms] [--preview-budget]");
    return 2;
}

try
{
    Run(operands, preview);
    return 0;
}
catch (Exception error) when (error is IOException or InvalidDataException or UnauthorizedAccessException or
    JsonException or ArgumentException or FormatException or OverflowException or
    KeyNotFoundException or InvalidOperationException)
{
    Console.Error.WriteLine($"UVSB check failed: {error.Message}");
    return 1;
}

static void Run(string[] operands, bool preview)
{
    const int MaxPngBytes = 16 << 20;
    var root = Path.Combine(operands[0], "storyboard");
    using var index = JsonDocument.Parse(ReadWithin(Path.Combine(root, "index.json"), 64 << 10));
    Require(index.RootElement.GetProperty("version").GetInt32() == 0, "Invalid storyboard index version");
    var filename = index.RootElement.GetProperty("charts").GetProperty("ramification").GetString()!;
    Require(filename == "official-excerpt.uvsb", "Not a pack generated by the local excerpt converter");
    var bytes = ReadWithin(Path.Combine(root, filename), StoryboardLimits.MaxSourceBytes);
    string script;
    try { script = new UTF8Encoding(false, true).GetString(bytes); }
    catch (DecoderFallbackException error) { throw new InvalidDataException("Invalid UVSB UTF-8", error); }
    var document = Checked(StoryboardDocument.Parse(script, filename));
    var sizes = new Dictionary<string, StoryboardTextureSize>(StringComparer.Ordinal);
    long pngBytes = 0, pixels = 0;
    Span<byte> header = stackalloc byte[33];
    foreach (var (id, relative) in document.Assets)
    {
        Require(relative == $"assets/{id}.png", $"Unexpected asset name: {relative}");
        using var image = File.OpenRead(Path.Combine(root, relative));
        var length = image.Length;
        Require(length >= header.Length && length <= MaxPngBytes, $"Invalid PNG byte count: {relative}");
        image.ReadExactly(header);
        Require(BinaryPrimitives.ReadUInt64BigEndian(header) == 0x89504e470d0a1a0aUL &&
            BinaryPrimitives.ReadUInt32BigEndian(header[8..]) == 13 &&
            header.Slice(12, 4).SequenceEqual("IHDR"u8), $"Invalid PNG header: {relative}");
        var width = BinaryPrimitives.ReadInt32BigEndian(header[16..]);
        var height = BinaryPrimitives.ReadInt32BigEndian(header[20..]);
        Require(width is > 0 and <= StoryboardLimits.MaxTextureDimension &&
            height is > 0 and <= StoryboardLimits.MaxTextureDimension, $"Invalid PNG dimensions: {relative}");
        sizes.Add(id, new(width, height));
        pngBytes += length;
        pixels += (long)width * height;
    }
    // Optional historical eager profile compatibility; no aggregate limit in streaming mode.
    if (preview)
    {
        Require(sizes.Count <= 128, "Preview asset count limit (128)");
        Require(pixels <= (96L << 20) / 4, "Preview texture pixel limit (96 MiB RGBA8)");
        Require(pngBytes <= (48L << 20), "Preview combined PNG byte limit (48 MiB)");
    }
    var sampler = Checked(StoryboardSampler.Compile(document, sizes));
    using var report = JsonDocument.Parse(ReadWithin(Path.Combine(root, "conversion-report.json"), 16 << 20));
    var summary = report.RootElement;
    Require(sampler.MaxDrawItems == summary.GetProperty("objects").GetInt32(), "Draw object count mismatch");
    Require(pixels == summary.GetProperty("texture_pixels").GetInt64(), "Texture pixel count mismatch");
    var bounds = summary.GetProperty("range_ms");
    int start = bounds[0].GetInt32(), end = bounds[1].GetInt32();
    Require(start >= 0 && end > start && (long)end - start <= 20_000, "Invalid excerpt range");
    var measureStart = operands.Length == 2 ? int.Parse(operands[1], CultureInfo.InvariantCulture) : start;
    Require(start <= measureStart && measureStart < end, "Measurement start is outside the excerpt");
    var draws = new List<StoryboardDrawItem>(sampler.MaxDrawItems);
    sampler.Sample((start - .5) / 1000, draws);
    Require(draws.Count == 0, "Objects visible before the excerpt");
    sampler.Sample(end / 1000d, draws);
    Require(draws.Count == 0, "Objects visible at the exclusive end");
    var peak = 0;
    var peakOpacity = 0;
    var unique = new HashSet<string>(StringComparer.Ordinal);
    for (var ms = measureStart; ms < end; ++ms)
    {
        sampler.Sample(ms / 1000d, draws);
        peak = Math.Max(peak, draws.Count);
        peakOpacity = Math.Max(peakOpacity, draws.Count(d => d.Opacity > 0));
        foreach (var draw in draws) unique.Add(draw.Id);
    }
    Require(peakOpacity > 0, "No nonzero-opacity sprites in measurement window");
    Console.WriteLine(FormattableString.Invariant(
        $"UVSB parse+compile OK: {sampler.MaxDrawItems} objects, {sizes.Count} PNGs, {pixels:N0} pixels, {pngBytes:N0} PNG bytes."));
    Console.WriteLine(FormattableString.Invariant(
        $"Sampled [{measureStart}, {end}) ms at 1 ms: {unique.Count} distinct objects, peak {peak} active / {peakOpacity} nonzero-opacity, before viewport culling."));
}

static byte[] ReadWithin(string path, int limit)
{
    using var stream = File.OpenRead(path);
    var length = stream.Length;
    Require(length > 0 && length <= limit, $"Invalid size for '{Path.GetFileName(path)}' (maximum {limit:N0} bytes)");
    var bytes = new byte[(int)length];
    stream.ReadExactly(bytes);
    Require(stream.ReadByte() < 0, $"'{Path.GetFileName(path)}' changed during read");
    return bytes;
}

static T Checked<T>(StoryboardResult<T> result) where T : class =>
    result.Value ?? throw new InvalidDataException(result.Diagnostic?.ToString());

static void Require(bool condition, string message)
{
    if (!condition) throw new InvalidDataException(message);
}
